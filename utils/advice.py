def get_advice(
    income: int,
    expenses: int,
    goals_count: int,
    history_count: int,
) -> str:

    if income > 0 and expenses > income:
        return random.choice(EXPENSES_OVER_INCOME_TIPS)

    if income > 0 and expenses < income:
        return random.choice(BALANCE_POSITIVE_TIPS)

    if goals_count > 0:
        return random.choice(SAVINGS_TIPS)

    if history_count >= 10:
        return random.choice(ACTIVE_USER_TIPS)

    if date.today().day <= 5:
        return random.choice(START_OF_MONTH_TIPS)

    return random.choice(GENERAL_TIPS)